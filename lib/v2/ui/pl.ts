/** Polish plural: 1 pytanie, 2-4 pytania (not 12-14), 5+ pytań. */
const plural = (n: number, one: string, few: string, many: string) => {
  if (n === 1) return one;
  const d = n % 10;
  const t = n % 100;
  return d >= 2 && d <= 4 && (t < 12 || t > 14) ? few : many;
};
const pyt = (n: number) => plural(n, "pytanie", "pytania", "pytań");
const umiej = (n: number) => plural(n, "umiejętność", "umiejętności", "umiejętności");

