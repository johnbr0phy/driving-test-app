# Image frequency of a superhet tuned to 100.0 MHz with a 10.7 MHz IF and the local
# oscillator above the signal.
F, IF = 100.0, 10.7
LO = F + IF
IMAGE = LO + IF
assert round(LO, 1) == 110.7 and round(IMAGE, 1) == 121.4
LOW = F - 2 * IF
assert round(LOW, 1) == 78.6

