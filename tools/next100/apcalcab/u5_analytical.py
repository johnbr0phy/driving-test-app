def _sign_change(fp, a, b, frm, to, n=40000):
    """First x in (a, b) where fp changes sign from frm to to (+1 or -1)."""
    prev = fp(a)
    for i in range(1, n + 1):
        x = a + (b - a) * i / n
        cur = fp(x)
        if cur == 0:
            continue
        if (prev > 0) == (frm > 0) and (cur > 0) == (to > 0):
            return round(x, 2)
        prev = cur
    return None


