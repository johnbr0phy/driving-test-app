def isq(i1, d1, d2):
    """Inverse square law: new intensity at d2."""
    return i1 * (d1 / d2) ** 2

_a = isq(40, 40, 80)    # 10
_b = isq(12, 72, 36)    # 48
_c = isq(90, 30, 45)    # 40
assert _a == 10 and _b == 48 and abs(_c - 40) < 1e-9

