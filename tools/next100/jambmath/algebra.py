def _f1(x):
    return 2 * x ** 3 - 5 * x ** 2 + 4 * x - 7


def _roots(a, b, c):
    d = b * b - 4 * a * c
    return sorted([(-b - sqrt(d)) / (2 * a), (-b + sqrt(d)) / (2 * a)])


def _g(x):
    return x ** 3 - 4 * x ** 2 + x + 6


