def _mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(2)) for j in range(2)] for i in range(2)]


def _comm(f):
    pts = [(1, 2), (3, -1), (0.5, 4), (-2, 5)]
    return all(abs(f(a, b) - f(b, a)) < 1e-12 for a, b in pts)


