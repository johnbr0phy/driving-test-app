def _gmedian(lower, width, freqs):
    n = sum(freqs)
    cum = 0
    for i, f in enumerate(freqs):
        if cum + f >= n / 2:
            return lower + i * width - 0.5 + (n / 2 - cum) / f * width
        cum += f


