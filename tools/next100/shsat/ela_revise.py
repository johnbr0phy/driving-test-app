def text(*paras):
    n, out = 0, []
    for p in paras:
        line = []
        for s in p:
            n += 1
            line.append(f"({n}) {s}")
        out.append(" ".join(line))
    return "\n\n".join(out)


def lock(key, *opts):
    o = list(opts)
    return dict(key=key, wrong=[x for x in o if x != key], lock=True, order=o)


