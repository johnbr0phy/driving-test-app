def _num(s):
    try:
        return float(s.replace(" ", ""))
    except ValueError:
        return None


def _build(items):
    rows = []
    for stem, key, wrong, pos, expl, notion, src in items:
        if pos is None:
            # Number answers: options in ascending order.
            opts = sorted([key] + wrong, key=_num)
            pos = opts.index(key)
        else:
            opts = list(wrong)
            opts.insert(pos, key)
        rows.append((stem, opts, pos, expl, notion, src))
    return rows


