def main():
    out, slot = [], 0
    for dom, test, skill, diff, basics, stem, key, wrong, expl in ITEMS:
        item = {"domain": dom, "test": test, "skill": skill, "difficulty": diff}
        if isinstance(key, dict):
            item["format"] = "numeric"
            if basics:
                item["basics"] = basics
            item["stem"] = stem
            item["numeric"] = {"answers": [key["numeric"]], "tolerance": 0}
            if key["whole"]:
                item["numeric"]["wholeNumber"] = True
        else:
            assert len(wrong) == 4 and key not in wrong, stem
            pos = slot % 5
            slot += 1
            opts = wrong[:pos] + [key] + wrong[pos:]
            item["format"] = "single"
            if basics:
                item["basics"] = basics
            item.update({"stem": stem, "options": opts, "correct": [pos]})
        item["explanation"] = expl
        out.append(item)
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "maths.json")
    with open(dst, "w") as f:
        json.dump(out, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"wrote {len(out)} maths items")


if __name__ == "__main__":
    main()
