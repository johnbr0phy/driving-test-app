def main():
    out, slot = [], 0
    for dom, test, skill, diff, basics, stem, key, wrong, expl in ITEMS:
        item = {"domain": dom, "test": test, "skill": skill, "difficulty": diff, "format": "single"}
        if basics:
            item["basics"] = basics
        if key.startswith("LOCK:"):
            opts, pos = list(wrong), int(key[5:])
            item.update({"stem": stem, "options": opts, "correct": [pos], "lockedOrder": True})
        else:
            assert len(wrong) == 3 and key not in wrong and len(set(wrong)) == 3, stem
            pos = slot % 4
            slot += 1
            opts = wrong[:pos] + [key] + wrong[pos:]
            item.update({"stem": stem, "options": opts, "correct": [pos]})
        item["explanation"] = expl
        out.append(item)
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "thinking.json")
    with open(dst, "w") as f:
        json.dump(out, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"wrote {len(out)} thinking items")


if __name__ == "__main__":
    main()
